"""One command from a clean clone to the running system on Minikube, ending with a smoke request.

    python deploy/up.py                 # start the cluster, build, deploy, wait, smoke test
    python deploy/up.py --down          # delete the cluster (the registry and the logs go with it)

Needs Docker Desktop, minikube and kubectl. Optional, read from the environment or from .env:
    ANTHROPIC_API_KEY                   without it the LLM service is deployed and reports not ready
    TELEGRAM_BOT_TOKEN, TELEGRAM_CHAT_ID  the human alert channel; without them alerts go only to the
                                        responder webhook (logged, and it can start the retrain Job)
Passwords of the cluster are generated on the first run and kept in deploy/.cluster.env (git-ignored):
the database volume remembers the first one, so a re-run must reuse it.

The image tag is the code commit (`-dirty` when src, rag, deploy or scripts have uncommitted changes).
"""

from __future__ import annotations

import argparse
import base64
import json
import secrets
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import kube
from kube import IMAGES, MLFLOW_IMAGE, NS, ROOT, kubectl, run, say

CLUSTER_ENV = ROOT / "deploy" / ".cluster.env"


def read_env_file(path: Path) -> dict[str, str]:
    values = {}
    if path.exists():
        for raw in path.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if line and not line.startswith("#") and "=" in line:
                key, value = line.split("=", 1)
                values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def settings() -> dict[str, str]:
    import os

    dotenv = read_env_file(ROOT / ".env")
    cluster = read_env_file(CLUSTER_ENV)
    changed = False
    for key in ("CLUSTER_POSTGRES_PASSWORD", "CLUSTER_GRAFANA_PASSWORD"):
        if key not in cluster:
            cluster[key] = secrets.token_urlsafe(18)
            changed = True
    if changed:
        CLUSTER_ENV.write_text(
            "# generated by deploy/up.py, git-ignored; delete it only together with the cluster\n"
            + "".join(f"{k}={v}\n" for k, v in cluster.items()),
            encoding="utf-8",
        )
    merged = {**dotenv, **{k: v for k, v in os.environ.items() if k in dotenv or k.startswith(
        ("ANTHROPIC_", "TELEGRAM_"))}}
    return {**merged, **cluster}


def secret_manifest(name: str, data: dict[str, str]) -> str:
    encoded = {k: base64.b64encode(v.encode("utf-8")).decode("ascii") for k, v in data.items()}
    return json.dumps(
        {"apiVersion": "v1", "kind": "Secret", "metadata": {"name": name, "namespace": NS},
         "type": "Opaque", "data": encoded}
    )


def alertmanager_config(cfg: dict[str, str]) -> dict[str, str]:
    telegram = bool(cfg.get("TELEGRAM_BOT_TOKEN") and cfg.get("TELEGRAM_CHAT_ID"))
    lines = [
        "global:",
        "  resolve_timeout: 5m",
        "route:",
        "  receiver: human",
        "  group_by: [alertname]",
        "  group_wait: 10s",
        "  group_interval: 1m",
        "  repeat_interval: 12h",
        "receivers:",
        "  - name: human",
        "    webhook_configs:",
        "      - url: http://responder:8080/alerts",
        "        send_resolved: true",
    ]
    files = {}
    if telegram:
        message = (
            "{{ range .Alerts }}[{{ .Status | toUpper }}] {{ .Labels.alertname }} "
            "({{ .Labels.severity }})\\n{{ .Annotations.summary }}\\n\\n{{ end }}"
            "Dashboard: kubectl -n mlops port-forward svc/grafana 3000:3000"
        )
        lines += [
            "    telegram_configs:",
            "      - bot_token_file: /etc/alertmanager/telegram_token",
            f"        chat_id: {int(cfg['TELEGRAM_CHAT_ID'])}",
            '        parse_mode: ""',
            "        send_resolved: true",
            f'        message: "{message}"',
        ]
        files["telegram_token"] = cfg["TELEGRAM_BOT_TOKEN"]
    files["alertmanager.yml"] = "\n".join(lines) + "\n"
    return files


def step(label: str, started: float) -> float:
    now = time.monotonic()
    say(f"  [{now - started:6.0f}s] {label}")
    return now


def ensure_minikube(memory: int, cpus: int) -> None:
    status = run(["minikube", "status", "--format={{.Host}}"], capture=True, check=False)
    if status.stdout.strip() == "Running":
        say("minikube is already running")
        return
    run(
        ["minikube", "start", "--driver=docker", f"--memory={memory}", f"--cpus={cpus}",
         "--kubernetes-version=v1.30.0"],
        check=True,
    )


def have_image(reference: str) -> bool:
    listing = run(["minikube", "image", "ls"], capture=True, check=False).stdout
    return any(line.strip().endswith(reference) or f"/{reference}" in line for line in listing.splitlines())


def stage_context(commit: str) -> Path:
    """A small build context: only what the images copy, without .venv, data and git history."""
    import shutil

    ctx = ROOT / "deploy" / ".build"
    if ctx.exists():
        shutil.rmtree(ctx)
    skip = shutil.ignore_patterns(".venv", "__pycache__", "data", "*.pyc", ".pytest_cache", ".ruff_cache")
    for source in ("src", "rag", "deploy/seed", "deploy/docker", "deploy/requirements"):
        shutil.copytree(ROOT / source, ctx / source, ignore=skip)
    for dockerfile in (ctx / "deploy" / "docker").glob("Dockerfile.*"):
        text = dockerfile.read_text(encoding="utf-8")
        dockerfile.write_text(text.replace("ARG GIT_COMMIT=unknown", f"ARG GIT_COMMIT={commit}"), encoding="utf-8")
    return ctx


def build_images(tag: str, commit: str, force: bool) -> None:
    ctx = None
    for name, dockerfile in IMAGES.items():
        reference = f"{name}:{tag}"
        if have_image(reference) and not force:
            say(f"image {reference} exists in minikube, not rebuilt")
            continue
        say(f"building {reference} (the first build downloads packages and takes minutes)")
        ctx = ctx or stage_context(commit)
        run(["minikube", "image", "build", "-t", reference, "-f", dockerfile, "."], cwd=ctx)
        if not have_image(reference):
            sys.exit(f"the build of {reference} did not produce an image, see the output above")
    if not have_image(MLFLOW_IMAGE) or force:
        say(f"building {MLFLOW_IMAGE}")
        ctx = ctx or stage_context(commit)
        run(["minikube", "image", "build", "-t", MLFLOW_IMAGE, "-f",
             "deploy/docker/Dockerfile.mlflow", "."], cwd=ctx)
        if not have_image(MLFLOW_IMAGE):
            sys.exit(f"the build of {MLFLOW_IMAGE} did not produce an image, see the output above")


def apply_secrets(cfg: dict[str, str]) -> None:
    user, password = "mlops", cfg["CLUSTER_POSTGRES_PASSWORD"]
    app = {
        "POSTGRES_USER": user,
        "POSTGRES_PASSWORD": password,
        "WAREHOUSE_URL": f"postgresql+psycopg2://{user}:{password}@postgres:5432/warehouse",
        "GRAFANA_ADMIN_PASSWORD": cfg["CLUSTER_GRAFANA_PASSWORD"],
    }
    if cfg.get("ANTHROPIC_API_KEY"):
        app["ANTHROPIC_API_KEY"] = cfg["ANTHROPIC_API_KEY"]
    else:
        say("ANTHROPIC_API_KEY is not set: the LLM service will report not ready")
    kubectl("apply", "-f", "-", input_text=secret_manifest("app-secrets", app))
    notify = {k: cfg[k] for k in ("TELEGRAM_BOT_TOKEN", "TELEGRAM_CHAT_ID") if cfg.get(k)}
    if notify:
        kubectl("apply", "-f", "-", input_text=secret_manifest("notify-secrets", notify))
    else:
        say("no Telegram bot configured: alerts go to the responder webhook only")
    kubectl("apply", "-f", "-", input_text=secret_manifest("alertmanager-config", alertmanager_config(cfg)))


def apply_rag_config() -> None:
    for name, source in (("rag-config", ["--from-file=config.yaml=rag/config.yaml"]),
                         ("rag-prompts", ["--from-file=rag/prompts"])):
        manifest = kubectl("create", "configmap", name, *source, "--dry-run=client", "-o", "yaml",
                           capture=True).stdout
        kubectl("apply", "-f", "-", input_text=manifest)


def apply_manifests(tag: str) -> None:
    rendered = run(["kubectl", "kustomize", "deploy/k8s"], capture=True).stdout
    kubectl("apply", "-f", "-", namespaced=False, input_text=rendered.replace("__TAG__", tag))


def smoke(tag: str, llm_expected: bool) -> None:
    sample = {
        "text": "Tariffs on steel and aluminum start tomorrow.", "text_len": 44, "link_count": 0,
        "caps_share": 0.05, "has_media": 0, "slot_index": 1, "weekday": 2,
        "minutes_since_open": 90, "sigma": 0.003, "last_bar_return": 0.0, "posts_prev_60min": 0,
    }
    with kube.forward("svc/ml-service", 8000) as url:
        status, body = kube.http("POST", f"{url}/predict", {"instances": [sample]})
        if status != 200:
            sys.exit(f"smoke request failed: {status} {body}")
        say(f"smoke /predict: HTTP {status}, model version {body['model_version']}, "
            f"image tag {body['image_tag']}, probability {body['predictions'][0]['probability']:.4f}, "
            f"alert {body['predictions'][0]['alert']}")
        if body["image_tag"] != tag:
            sys.exit(f"the service runs image tag {body['image_tag']}, expected {tag}")
    if llm_expected:
        with kube.forward("svc/llm-service", 8000) as url:
            status, body = kube.http(
                "POST", f"{url}/ask", {"question": "What did he say about steel tariffs?", "top_k": 3},
                timeout=120)
            if status == 200:
                say(f"smoke /ask: HTTP 200, {body['tokens_in']} tokens in, cost ${body['cost_usd']:.5f}, "
                    f"{len(body['sources'])} sources")
            else:
                say(f"smoke /ask: HTTP {status} {str(body)[:200]}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--down", action="store_true", help="delete the cluster")
    ap.add_argument("--memory", type=int, default=4096, help="MB for a new minikube cluster")
    ap.add_argument("--cpus", type=int, default=2)
    ap.add_argument("--rebuild", action="store_true", help="build the images even if they exist")
    ap.add_argument("--no-smoke", action="store_true")
    args = ap.parse_args()

    for tool in ("docker", "minikube", "kubectl", "git"):
        kube.need(tool)
    if args.down:
        run(["minikube", "delete"])
        return 0

    started = time.monotonic()
    tag, commit = kube.image_tag()
    say(f"commit {commit}, image tag {tag}")
    cfg = settings()
    ensure_minikube(args.memory, args.cpus)
    step("cluster is up", started)
    build_images(tag, commit, args.rebuild)
    step("images are built", started)

    kubectl("apply", "-f", "deploy/k8s/namespace.yaml", namespaced=False)
    apply_secrets(cfg)
    apply_rag_config()
    for job in ("model-bootstrap", "rag-ingest"):
        kubectl("delete", "job", job, "--ignore-not-found", "--wait=true")
    apply_manifests(tag)
    step("manifests applied", started)

    for deployment in ("postgres", "mlflow"):
        kubectl("rollout", "status", f"deployment/{deployment}", "--timeout=600s")
    step("postgres and the tracking server are ready", started)
    kube.wait_job("model-bootstrap", 900)
    step("registry filled: model registered with the alias champion", started)
    kube.wait_job("rag-ingest", 1200)
    step("vector index built", started)
    llm_expected = bool(cfg.get("ANTHROPIC_API_KEY"))
    waiting = ["ml-service", "prometheus", "pushgateway", "alertmanager", "grafana", "responder"]
    if llm_expected:
        waiting.append("llm-service")
    for deployment in waiting:
        kubectl("rollout", "status", f"deployment/{deployment}", "--timeout=600s")
    step("all deployments are ready", started)

    if not args.no_smoke:
        smoke(tag, llm_expected)
    say("")
    say(kube.pods_text())
    total = time.monotonic() - started
    say(f"done in {total / 60:.1f} minutes")
    say("UIs: python deploy/ports.py  (Grafana :3000, Prometheus :9090, Alertmanager :9093, MLflow :5000)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
